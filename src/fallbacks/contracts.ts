/**
 * THE FALLBACK CONTRACT LIBRARY — SIXTEEN FAMILIES, SEVENTY CONTRACTS, AND THE
 * OBJECT EVERY LATER FALLBACK RENDERING IS READ OUT OF.
 *
 * No `FB-*` registry existed before this file. `registries/generated/` holds
 * fourteen families and fallbacks is not one of them, so nothing downstream
 * could name a contract without inventing it. §38.4 is transcribed here whole:
 * the library index at L82412 (header) to L82429 (the last family row), and
 * the seventy contracts from `FB-NET-001` at L82503 to `FB-PLAT-004` at L84810.
 *
 * ── SEVENTY, PROVED FROM BOTH SIDES ────────────────────────────────────────
 * This is one of the counts that DOES reconcile, and it reconciles because two
 * independent readings agree rather than because a literal says so:
 *
 *   side A — the library index's own `Contracts` column, sixteen rows,
 *            summing to seventy;
 *   side B — the seventy `**Contract `FB-*`**` headings actually present, whose
 *            identifier prefixes fall into sixteen groups whose sizes are the
 *            same sixteen numbers.
 *
 * `fallback-contracts.test.ts` asserts it from both sides and from the frozen
 * source, never from `FALLBACK_CONTRACTS.length` compared to a literal 70 —
 * which is the tautology shape this build has been bitten by before.
 *
 * ── TWENTY-FOUR ROWS, HEADER-KEYED ─────────────────────────────────────────
 * `cells` is a TOTAL `Record<RenderedRow, string>`. A blank cell is
 * untypeable, a dropped row is a type error, and nothing here is positional —
 * see `template.ts` for the twenty-six/twenty-four ruling and why this build
 * renders twenty-four.
 *
 * All seventy render the same twenty-four labels in the same order; that was
 * measured across all seventy against the frozen source, not sampled.
 *
 * ── WHAT THIS FILE DOES NOT DO ─────────────────────────────────────────────
 * It does not parse `Criticality` into a token. The declared vocabulary is
 * four values (`DECLARED_CRITICALITY_VALUES`); the library index uses a fifth,
 * `Security-critical`, at L82417; and the contracts' own cells are free prose
 * that sometimes names two classes at once. The cell is stored verbatim.
 *
 * It does not resolve `DEC-FB-008`, and it does not attach it. See
 * `disclosure.ts`.
 *
 * This module is data. It computes nothing and decides nothing.
 */

