/**
 * THE FAILURE CATALOGUE — SECTION 43.2, SIX FAMILIES OF `FAIL-AI-*` MODES,
 * EACH FAMILY CARRYING THREE ATTRIBUTE TABLES OVER THE SAME ROWS.
 *
 * Every cell below is a verbatim transcription of the source cell at the line
 * the record itself names, and `tests/unit/ai-failures.test.ts` fetches each
 * cell back THROUGH that locator, so a wrong line and a wrong cell fail the
 * same assertion. Nothing here is paraphrased and nothing is summarised.
 *
 * ── WHAT THE THREE TABLES PER FAMILY CARRY ─────────────────────────────────
 * The first names the failure, its detector, its operational severity and the
 * exact strings each surface shows. The second carries the gate, the retry
 * limit, the breaker, the alternate model and the partial-output rule. The
 * third carries the fallback ladder, the terminal safe state, recovery and
 * reconciliation. Same rows, same order, in all three — asserted rather than
 * assumed, because a row present in one table and absent from another would
 * leave attributes unstated and `AC-43-101` (L89973) forbids exactly that.
 *
 * ── HOW A ROW RESOLVES A SPINE ATTRIBUTE, AND WHERE THE JUDGEMENT IS ───────
 * `AC-43-101` requires each row to resolve every spine attribute as inherited,
 * deviated or owed. The source's tables answer only some of the spine's items
 * by column, so the binding between the two is stated here, once per item,
 * with the reason — and it is a BUILD JUDGEMENT, not a source fact. It is
 * written down so a reviewer can disagree with one binding rather than having
 * to re-derive all of them.
 *
 * Two kinds of binding, and the distinction is what stops every row from
 * resolving the same way:
 *
 *   - `selects` — the spine fixes the rule and the row picks from inside it.
 *     Item 1's default already enumerates the detector sources; a row naming
 *     one of them has not displaced anything. The source reads its own
 *     catalogue this way at L89915, where a row with a filled Detection cell
 *     is described as inheriting: "a detector notices rather than a person".
 *   - `displaces` — the row states its own answer where the spine fixed a
 *     different one, or fixed none. Item 3 is the clearest: the spine fixes no
 *     string, so every row's message is a deviation, which is again how the
 *     source reads it at L89915.
 *
 * Above both: a cell pointing at the open register resolves `owed`, whatever
 * its binding. That is the third fate, and it is detected on the tables' own
 * idiom — the bare token `Register`, or one of the register's identifiers.
 *
 * ── ONE COLUMN BINDS TO NO ITEM ON ITS OWN, AND SAYING SO IS THE POINT ─────
 * The `First fallback` column names which rung of the ladder a row enters
 * first. Spine items 8 and 9 say what those rungs ARE, and both say "Always" —
 * item 8's deterministic layer "is never unavailable", item 9's escalation is
 * "always the authored escalation path". So the column selects among rungs the
 * spine already fixed rather than displacing either, and both items bind to it
 * as `selects`. It is written here rather than left implicit because the
 * alternative reading — that a filled `First fallback` cell deviates items 8
 * and 9 on all sixty rows — is defensible and produces a different catalogue.
 */

