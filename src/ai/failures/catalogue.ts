const BY_ID = new Map<string, CatalogueRow>(FAILURE_CATALOGUE.map((r) => [r.id, r]))

export function catalogueRow(id: string): CatalogueRow {
  const found = BY_ID.get(id)
  if (!found) throw new Error(`No catalogued failure is registered for ${id}.`)
  return found
}

const BINDING = new Map<SpineItemNumber, SpineBinding>(SPINE_BINDINGS.map((b) => [b.item, b]))

/**
 * The tables' own idiom for "this value is owed to the open register": the
 * bare token `Register`, or one of the register's identifiers. A cell naming a
 * decision that is NOT in the register — `DEC-AGENTLC-001` on `FAIL-AI-20`'s
 * reconciliation, for instance — is a deviation that happens to cite an open
 * decision elsewhere, and reading it as owed here would put an attribute in
 * the wrong register.
 */
function pointsAtTheRegister(cell: string): boolean {
  if (/(^|[\s(])Register\b/.test(cell)) return true
  return REGISTER_IDS.some((id) => cell.includes(id))
}

export type SpineResolution = 'inherited' | 'deviated' | 'owed'

/**
 * How one row resolves one spine attribute. Total over `SpineItemNumber`,
 * because `BINDING` is built from `SPINE_BINDINGS` and the test asserts that
 * list IS `SPINE_ITEM_NUMBERS`; a miss throws rather than defaulting to
 * `inherited`, which is the shape that would make `AC-43-101` unfalsifiable.
 */
export function spineResolution(row: CatalogueRow, item: SpineItemNumber): SpineResolution {
  const binding = BINDING.get(item)
  if (!binding) throw new Error(`No spine binding is registered for item ${String(item)}.`)
  if (binding.columns.length === 0) return 'inherited'
  if (binding.columns.some((c) => pointsAtTheRegister(row.cells[c]))) return 'owed'
  return binding.kind === 'selects' ? 'inherited' : 'deviated'
}

export function spineResolutions(row: CatalogueRow): Readonly<Record<SpineItemNumber, SpineResolution>> {
  return Object.fromEntries(
    SPINE_ITEM_NUMBERS.map((item) => [item, spineResolution(row, item)]),
  ) as Record<SpineItemNumber, SpineResolution>
}

/**
 * Re-derives the severity assignment from the row's own cell. Exported so the
 * stored assignment can be checked against the parser rather than trusted, and
 * so a later surface can ask the question without reaching into the record.
 */
export function severityOf(row: CatalogueRow): SeverityAssignment | null {
  return severityAssignment(row.cells.operationalSeverity)
}

/**
 * THIS MODULE'S SIDE OF THE `AC-43-301` SEAM (L90840), AND NOTHING MORE.
 *
 * `AC-43-301` requires that during any catalogued failure, all five surfaces
 * render a state drawn from the operating-mode vocabulary and that no two
 * surfaces contradict. That vocabulary is a SEPARATE object owned elsewhere in
 * this wave, and it is deliberately not imported, restated or validated
 * against here — a second copy of a closed vocabulary is a second thing to
 * keep true, and the copy is always the one that goes stale.
 *
 * What this module can honestly say is which mode identifiers its own cells
 * name. It returns them as opaque strings. Whoever owns the vocabulary is
 * responsible for the membership check, and this is the list they must cover.
 */
export function aiModesNamed(row: CatalogueRow): readonly string[] {
  return [...new Set([...JSON.stringify(row.cells).matchAll(/AIMODE-\d+/g)].map((m) => m[0]))].sort()
}

/** Every mode identifier the catalogue's own cells name, across all its rows. */
export function aiModesNamedByCatalogue(): readonly string[] {
  return [...new Set(FAILURE_CATALOGUE.flatMap(aiModesNamed))].sort()
}
